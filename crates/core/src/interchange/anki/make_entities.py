"""Writes entities.rs, the table of HTML's named character references.

Run from this folder with any Python 3:  python3 -I make_entities.py
The names and values are those of the WHATWG HTML standard, as Python's
standard library has them (html.entities.html5).
"""

from html.entities import html5

def rust(text):
    return "".join(
        c if (c.isascii() and c.isprintable() and c not in '"\\') else "\\u{%X}" % ord(c)
        for c in text
    )

names = sorted(html5, key=lambda n: n.encode())
with open("entities.rs", "w") as out:
    out.write("//! HTML's named character references (generated by `make_entities.py`\n")
    out.write("//! from the WHATWG list in Python's `html.entities.html5`; do not edit).\n")
    out.write("//! Each name with its `;` when the reference needs one, sorted by bytes.\n\n")
    out.write("pub(super) static ENTITIES: [(&str, &str); %d] = [\n" % len(names))
    for name in names:
        out.write('    ("%s", "%s"),\n' % (rust(name), rust(html5[name])))
    out.write("];\n")
